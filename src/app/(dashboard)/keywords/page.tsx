"use client";

import { useState } from "react";
import { useRouter } from "next/navigation";
import { Badge, Button, Card, CardHeader, EmptyState, Input, Spinner } from "@/components/ui";
import type { KeywordResearchResult } from "@/lib/seo/keywords";
import { postJson, UnauthorizedError } from "@/lib/api-client";

function IntentBadge({ intent }: { intent: string | null }) {
  if (!intent) return <span className="text-slate-500">—</span>;
  const tone =
    intent === "transactional" ? "success" : intent === "commercial" ? "info" : intent === "navigational" ? "warning" : "neutral";
  return <Badge tone={tone as never}>{intent}</Badge>;
}

export default function KeywordResearchPage() {
  const router = useRouter();
  const [term, setTerm] = useState("");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [result, setResult] = useState<KeywordResearchResult | null>(null);
  const [aiIdeas, setAiIdeas] = useState<{ ideas: { term: string; intent: string; rationale: string }[]; provider: string; model: string; isFallback: boolean } | null>(null);
  const [aiLoading, setAiLoading] = useState(false);
  const [aiError, setAiError] = useState<string | null>(null);

  async function runResearch() {
    if (!term.trim()) return;
    setLoading(true);
    setError(null);
    try {
      const data = await postJson<KeywordResearchResult>("/api/seo/keywords", { term: term.trim() });
      setResult(data);
    } catch (err) {
      if (err instanceof UnauthorizedError) {
        router.push("/login");
        return;
      }
      setError(err instanceof Error ? err.message : "Couldn't fetch keyword data. Please try again.");
    } finally {
      setLoading(false);
    }
  }

  async function generateAiIdeas() {
    if (!term.trim()) return;
    setAiLoading(true);
    setAiError(null);
    try {
      const data = await postJson<{
        ideas: { term: string; intent: string; rationale: string }[];
        provider: string;
        model: string;
        isFallback: boolean;
      }>("/api/seo/keywords/ideas", { term: term.trim() });
      setAiIdeas(data);
    } catch (err) {
      if (err instanceof UnauthorizedError) {
        router.push("/login");
        return;
      }
      setAiError(err instanceof Error ? err.message : "Couldn't generate keyword ideas. Please try again.");
    } finally {
      setAiLoading(false);
    }
  }

  const rows = result ? [result.seed, ...result.related] : [];

  return (
    <div className="flex flex-col gap-6">
      <div>
        <h1 className="text-xl font-semibold text-slate-900 dark:text-white">Keyword Research</h1>
        <p className="mt-1 text-sm text-slate-500 dark:text-slate-400">
          Find related queries with live search metrics. Connect DataForSEO in Admin Settings to retrieve volume, difficulty, and CPC.
        </p>
      </div>

      <Card className="p-5">
        <form
          onSubmit={(e) => {
            e.preventDefault();
            runResearch();
          }}
          className="flex flex-col gap-3 sm:flex-row"
        >
          <Input
            placeholder="e.g. project management software"
            value={term}
            onChange={(e) => {
              setTerm(e.target.value);
              setAiIdeas(null);
              setAiError(null);
            }}
            aria-label="Seed keyword"
          />
          <Button type="submit" disabled={loading || !term.trim()}>
            {loading ? <Spinner /> : "Research"}
          </Button>
          <Button type="button" variant="secondary" onClick={generateAiIdeas} disabled={aiLoading || !term.trim()}>
            {aiLoading ? <Spinner /> : "AI keyword ideas"}
          </Button>
        </form>
        {error && <p className="mt-3 text-sm text-red-600 dark:text-red-400">{error}</p>}
        {aiError && <p role="alert" className="mt-3 text-sm text-red-600 dark:text-red-400">{aiError}</p>}
      </Card>

      {aiIdeas && (
        <Card>
          <CardHeader
            title="AI keyword ideas"
            description={`Generated by ${aiIdeas.provider} (${aiIdeas.model})${aiIdeas.isFallback ? " via fallback provider" : ""}. These are suggestions, not live search metrics.`}
          />
          <div className="divide-y divide-slate-100 dark:divide-slate-800">
            {aiIdeas.ideas.map((idea, index) => (
              <div key={`${idea.term}-${index}`} className="flex flex-col gap-1 px-5 py-3 sm:flex-row sm:items-start sm:gap-3">
                <span className="min-w-0 flex-1 text-sm font-medium text-slate-800 dark:text-slate-200">{idea.term}</span>
                <Badge tone={idea.intent === "transactional" ? "success" : idea.intent === "commercial" ? "info" : idea.intent === "navigational" ? "warning" : "neutral"}>{idea.intent}</Badge>
                <span className="text-sm text-slate-500 dark:text-slate-400 sm:max-w-sm">{idea.rationale}</span>
              </div>
            ))}
          </div>
        </Card>
      )}

      <Card>
        <CardHeader
          title="Results"
          description={
            result?.isMockData
              ? result.dataProvider?.includes("fallback")
                ? `Live provider (${result.dataProvider.replace(" (fallback: mock)", "")}) timed out or failed. Showing simulated data.`
                : "Showing simulated mock data — no keyword data provider is connected yet."
              : result?.dataProvider === "dataforseo"
                ? "Live keyword suggestions, search volume, difficulty, and CPC from DataForSEO."
                : result
                  ? result.related.length === 0
                    ? "OpenSERP returned no related-search features for this query. Try another seed or use AI keyword ideas. Connect DataForSEO for search metrics."
                    : "Related queries come from live SERP data. Connect DataForSEO to add search volume, difficulty, and CPC."
                  : undefined
          }
        />
        {!result && !loading && (
          <EmptyState
            title="No keywords yet"
            description="Enter a seed keyword above to discover related queries and available search metrics."
          />
        )}
        {result && (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-sm">
              <thead>
                <tr className="border-b border-slate-100 text-xs uppercase tracking-wide text-slate-500 dark:border-slate-800">
                  <th className="px-5 py-3 font-medium">Keyword</th>
                  <th className="px-5 py-3 font-medium">Volume</th>
                  <th className="px-5 py-3 font-medium">Difficulty</th>
                  <th className="px-5 py-3 font-medium">CPC</th>
                  <th className="px-5 py-3 font-medium">Intent</th>
                </tr>
              </thead>
              <tbody>
                {rows.map((row, i) => (
                  <tr
                    key={row.term}
                    className={`border-b border-slate-50 last:border-0 dark:border-slate-800/60 ${
                      i === 0 ? "bg-slate-50/60 font-medium dark:bg-slate-800/30" : ""
                    }`}
                  >
                    <td className="px-5 py-3 text-slate-800 dark:text-slate-200">
                      {row.term}
                      {i === 0 && (
                        <span className="ml-2">
                          <Badge tone="neutral">seed</Badge>
                        </span>
                      )}
                    </td>
                    <td className="px-5 py-3 text-slate-600 dark:text-slate-400">
                      {row.searchVolume?.toLocaleString() ?? "—"}
                    </td>
                    <td className="px-5 py-3 text-slate-600 dark:text-slate-400">{row.difficulty ?? "—"}</td>
                    <td className="px-5 py-3 text-slate-600 dark:text-slate-400">
                      {row.cpc != null ? `$${row.cpc.toFixed(2)}` : "—"}
                    </td>
                    <td className="px-5 py-3">
                      <IntentBadge intent={row.intent} />
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Card>
    </div>
  );
}
